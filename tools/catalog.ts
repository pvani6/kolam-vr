// Run from the project folder:  node --experimental-strip-types tools/catalog.ts
// Plain woven kolams on many traditional dot shapes.
import { rectDots, diamondDots, octagonDots, crossDots, design, kolamCurves, traceKolam, ringDots, type P2, type KolamDesign } from '../src/kolam-patterns.ts';
import { writeFileSync } from 'node:fs';
type F = { label: string; layout: string; dots: P2[] };
const R = (w: number, h: number): F => ({ label: `${w} x ${h} dots`, layout: `{ type: 'rect', w: ${w}, h: ${h} }`, dots: rectDots(w, h) });
const D = (r: number): F => ({ label: `${2*r+1}-1 dots`, layout: `{ type: 'diamond', r: ${r} }`, dots: diamondDots(r) });
const O = (r: number, cut: number): F => ({ label: `${2*r+1} x ${2*r+1} octagon`, layout: `{ type: 'octagon', r: ${r}, cut: ${cut} }`, dots: octagonDots(r, cut) });
const C = (arm: number, thick: number): F => ({ label: `cross of ${crossDots(arm, thick).length} dots`, layout: `{ type: 'cross', arm: ${arm}, thick: ${thick} }`, dots: crossDots(arm, thick) });
const FAMS: F[] = [
  D(1), R(2,2), R(2,3), R(3,3), D(2), R(3,4), R(4,4), R(3,5), R(5,5), R(4,6), D(3), O(2,1),
  R(6,6), R(5,7), C(2,1), R(7,7), D(4), O(3,2), C(2,3), R(8,8), R(9,9), O(4,3), D(5), D(6),
];
type E = F & { style: string; circled: P2[]; d: KolamDesign };
const ok: E[] = [];
const odd = (v: number) => Math.abs(v) % 2 === 1;
const even = (v: number) => Math.abs(v) % 2 === 0;
const STYLES: [string, (p: P2) => boolean][] = [
  ['circled dots', (p) => odd(p.x) && odd(p.y)],
  ['circled dots II', (p) => even(p.x) && even(p.y)],
];
for (const f of [...FAMS].sort((a, b) => a.dots.length - b.dots.length)) {
  try { traceKolam(design('x', '', f.dots)); } catch (e) { console.log('skip', f.label); continue; }
  ok.push({ ...f, style: 'woven', circled: [], d: design('x', '', f.dots) });
  if (f.dots.length < 13) continue;
  const has = new Set(f.dots.map((d) => `${d.x},${d.y}`));
  const edge = (p: P2) => [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([a, b]) => !has.has(`${p.x + a},${p.y + b}`));
  const seen = new Set<string>();
  for (const [style, rule] of STYLES) {
    const circled = f.dots.filter((p) => !edge(p) && rule(p));
    const sig = circled.map((p) => `${p.x},${p.y}`).join('|');
    if (circled.length < 2 || seen.has(sig)) continue;
    seen.add(sig);
    const d = design('x', '', f.dots, ringDots(circled));
    let loops;
    try { loops = traceKolam(d).loops; } catch { continue; }
    // Reject if any dot that we did NOT circle got cut off from the weave.
    const want = new Set(circled.map((p) => `${p.x},${p.y}`));
    const floating = loops.some((l) => l.length === 4 && !want.has(`${(l[0].x + l[1].x + l[2].x + l[3].x) / 4},${(l[0].y + l[1].y + l[2].y + l[3].y) / 4}`));
    if (floating) continue;
    ok.push({ ...f, style, circled, d });
  }
}
const cell = 200, cols = 7;
let svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${cell*cols}" height="${cell*Math.ceil(ok.length/cols)}"><rect width="100%" height="100%" fill="#2a1416"/>`;
ok.forEach((f, i) => {
  const d = f.d;
  const ox=(i%cols)*cell+cell/2, oy=Math.floor(i/cols)*cell+cell/2-10;
  const xs=f.dots.map(p=>p.x), ys=f.dots.map(p=>p.y);
  const cx=(Math.min(...xs)+Math.max(...xs))/2, cy=(Math.min(...ys)+Math.max(...ys))/2;
  const ext=Math.max(Math.max(...xs)-Math.min(...xs), Math.max(...ys)-Math.min(...ys))+1; const s=(cell*0.74)/ext;
  const T=(p:P2)=>`${(ox+(p.x-cx)*s).toFixed(1)},${(oy-(p.y-cy)*s).toFixed(1)}`;
  for (const l of kolamCurves(d)) svg += `<polygon points="${l.map(T).join(' ')}" fill="none" stroke="#ffe2a0" stroke-width="${Math.max(1.4,s*0.075)}"/>`;
  for (const p of f.dots) { const [x,y]=T(p).split(','); svg += `<circle cx="${x}" cy="${y}" r="${Math.max(1.6,s*0.07)}" fill="#fff4dc"/>`; }
  svg += `<text x="${ox}" y="${oy+cell/2-2}" fill="#c9a" font-size="12" text-anchor="middle" font-family="sans-serif">${i+1}. ${f.label}${f.style === 'woven' ? '' : ' · ' + f.style}</text>`;
});
writeFileSync(new URL('catalog-preview.svg', import.meta.url), svg+'</svg>');
let out = `/**
 * Pulli kolam catalogue (generated by tools/catalog.ts).
 * Each kolam = a traditional dot shape + a complete woven lattice: the line
 * crosses between every pair of neighbouring dots, loops round the outer
 * dots, and never touches itself. Drawn by our own generator.
 */
export type Layout =
  | { type: 'rect'; w: number; h: number }
  | { type: 'diamond'; r: number }
  | { type: 'octagon'; r: number; cut: number }
  | { type: 'cross'; arm: number; thick: number };
export interface CatalogEntry {
  family: string;
  layout: Layout;
  style: string;
  /** Dots the line curls right round (a circle), while it weaves round the rest. */
  circled: [number, number][];
}
export const CATALOG: CatalogEntry[] = [
`;
for (const f of ok) out += `  { family: '${f.label}', layout: ${f.layout}, style: '${f.style}', circled: [${f.circled.map((p) => `[${p.x}, ${p.y}]`).join(', ')}] },\n`;
writeFileSync(new URL('../src/kolam-catalog.ts', import.meta.url), out + '];\n');
