// Run from the project folder:  node --experimental-strip-types tools/solve.ts
// For each dot shape: how many separate lines it starts with, and the fewest
// turns (mirrors between dots) that join everything into ONE line.
import { rectDots, diamondDots, octagonDots, crossDots, design, traceKolam, kolamCurves, type P2, type MirrorType } from '../src/kolam-patterns.ts';
import { writeFileSync } from 'node:fs';
type F = { label: string; layout: string; dots: P2[] };
const R = (w: number, h: number): F => ({ label: `${w} x ${h} dots`, layout: `{ type: 'rect', w: ${w}, h: ${h} }`, dots: rectDots(w, h) });
const D = (r: number): F => ({ label: `${2*r+1}-1 dots`, layout: `{ type: 'diamond', r: ${r} }`, dots: diamondDots(r) });
const O = (r: number, cut: number): F => ({ label: `${2*r+1} x ${2*r+1} octagon`, layout: `{ type: 'octagon', r: ${r}, cut: ${cut} }`, dots: octagonDots(r, cut) });
const C = (arm: number, thick: number): F => ({ label: `cross of ${crossDots(arm, thick).length} dots`, layout: `{ type: 'cross', arm: ${arm}, thick: ${thick} }`, dots: crossDots(arm, thick) });
const FAMS = [R(2,2), R(2,3), R(3,3), R(2,4), R(3,4), R(4,4), D(2), R(3,5), R(4,5), O(2,1), R(5,5), R(4,6), D(3), C(2,1), R(5,6), R(6,6), O(3,2), R(5,7), D(4), R(7,7)];
const key = (x: number, y: number) => `${Math.round(x*2)},${Math.round(y*2)}`;
let seed = 7;
const rnd = () => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed / 0x7fffffff; };

function interiorGaps(dots: P2[]): P2[] {
  const has = new Set(dots.map(d => `${d.x},${d.y}`));
  const g: P2[] = [];
  for (const d of dots) { if (has.has(`${d.x+1},${d.y}`)) g.push({ x: d.x+0.5, y: d.y }); if (has.has(`${d.x},${d.y+1}`)) g.push({ x: d.x, y: d.y+0.5 }); }
  return g;
}
const lines = (dots: P2[], m: Map<string, MirrorType>) => { try { return traceKolam(design('','',dots,m)).loops.length; } catch { return 99; } };

const results: any[] = [];
for (const f of FAMS) {
  const gaps = interiorGaps(f.dots);
  const start = lines(f.dots, new Map());
  if (start <= 1) { console.log(f.label.padEnd(16), 'already one line — skip'); continue; }
  // Greedy + random restarts: add the turn that most reduces the line count.
  let best: [string, MirrorType][] | null = null;
  for (let attempt = 0; attempt < 400; attempt++) {
    const m = new Map<string, MirrorType>();
    let cur = start;
    for (let step = 0; step < 40 && cur > 1; step++) {
      const opts: [string, MirrorType, number][] = [];
      for (const g of gaps) { const k = key(g.x, g.y); if (m.has(k)) continue;
        for (const t of ['wall','bridge'] as MirrorType[]) { m.set(k, t); opts.push([k, t, lines(f.dots, m)]); m.delete(k); } }
      const minL = Math.min(...opts.map(o => o[2]));
      const good = opts.filter(o => o[2] === minL && minL < cur);
      const pick = good.length ? good[Math.floor(rnd()*good.length)] : opts[Math.floor(rnd()*opts.length)];
      m.set(pick[0], pick[1]); cur = pick[2];
    }
    if (cur === 1 && (!best || m.size < best.length)) best = [...m.entries()];
  }
  console.log(f.label.padEnd(16), 'starts with', start, 'lines → solved with', best ? best.length : 'NONE', 'turns');
  if (best) results.push({ f, start, best });
}

let out = `/**
 * One-line puzzles (generated by tools/solve.ts).
 * start = separate lines in the plain woven kolam; par = fewest turns we found
 * that join it into ONE line; solution = one such set of turns (used for hints).
 * Turn keys are midpoints in doubled coordinates "X,Y".
 */
import type { Layout } from './kolam-catalog.js';
export interface Puzzle {
  family: string;
  layout: Layout;
  start: number;
  par: number;
  solution: [string, 'wall' | 'bridge'][];
}
export const PUZZLES: Puzzle[] = [
`;
for (const r of results) out += `  { family: '${r.f.label}', layout: ${r.f.layout}, start: ${r.start}, par: ${r.best.length}, solution: ${JSON.stringify(r.best).replace(/"/g, "'")} },\n`;
writeFileSync(new URL('../src/kolam-puzzles.ts', import.meta.url), out + '];\n');

// Preview: start vs solved
const cell = 200;
let svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${cell*2}" height="${cell*results.length}"><rect width="100%" height="100%" fill="#2a1416"/>`;
const COLS = ['#ffd98a','#ff7aa2','#7bd389','#5ec8f2','#b388ff','#ffb347','#f25e5e','#9ad0ff','#e0e070','#ff9de6'];
results.forEach((r, i) => {
  [new Map(), new Map(r.best)].forEach((m, j) => {
    const d = design('','',r.f.dots,m as any);
    const ox = j*cell+cell/2, oy = i*cell+cell/2-8;
    const xs=r.f.dots.map((p:P2)=>p.x), ys=r.f.dots.map((p:P2)=>p.y);
    const cx=(Math.min(...xs)+Math.max(...xs))/2, cy=(Math.min(...ys)+Math.max(...ys))/2;
    const ext=Math.max(Math.max(...xs)-Math.min(...xs), Math.max(...ys)-Math.min(...ys))+1; const s=(cell*0.74)/ext;
    const T=(p:P2)=>`${(ox+(p.x-cx)*s).toFixed(1)},${(oy-(p.y-cy)*s).toFixed(1)}`;
    kolamCurves(d).forEach((l, k) => svg += `<polygon points="${l.map(T).join(' ')}" fill="none" stroke="${COLS[k%COLS.length]}" stroke-width="${Math.max(1.4,s*0.08)}"/>`);
    for (const p of r.f.dots) { const [x,y]=T(p).split(','); svg += `<circle cx="${x}" cy="${y}" r="${Math.max(1.6,s*0.07)}" fill="#fff4dc"/>`; }
    svg += `<text x="${ox}" y="${oy+cell/2-2}" fill="#c9a" font-size="11" text-anchor="middle" font-family="sans-serif">${r.f.label} · ${j? 'solved, '+r.best.length+' turns' : r.start+' lines'}</text>`;
  });
});
writeFileSync(new URL('puzzles-preview.svg', import.meta.url), svg + '</svg>');
